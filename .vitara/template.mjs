#!/usr/bin/env node
// Template-only tooling (removed by Vitara when a project is created).
// Mirrors what the Vitara server writes, per .vitara/TEMPLATE_CONTRACT.md (v1).
//
//   node .vitara/template.mjs generate   rewrite src/styles/brand.css and the index.html brand block from brand.json
//   node .vitara/template.mjs check      verify the repo follows the contract (exit 1 on any problem)

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const p = (...s) => join(ROOT, ...s)
const readJson = (f) => JSON.parse(readFileSync(p(f), 'utf8'))

// ---- contract constants (section 2.4 and 4) ----
const SANS = ['Inter', 'Roboto', 'Open Sans', 'Lato', 'Montserrat', 'Poppins', 'Nunito', 'Raleway', 'Work Sans', 'DM Sans',
  'Manrope', 'Plus Jakarta Sans', 'Rubik', 'IBM Plex Sans', 'Noto Sans', 'Cairo']
const SERIF = ['Playfair Display', 'Merriweather', 'Lora']
const CODES = { en: 'ltr', hi: 'ltr', es: 'ltr', 'pt-BR': 'ltr', fr: 'ltr', de: 'ltr', id: 'ltr', tr: 'ltr', ru: 'ltr', it: 'ltr',
  ar: 'rtl', pl: 'ltr', nl: 'ltr', ro: 'ltr', 'ar-MA': 'rtl', sr: 'ltr', sv: 'ltr', el: 'ltr', da: 'ltr', fi: 'ltr' }
const BRAND_KEYS = ['app_name', 'tagline', 'primary_color', 'accent_color', 'font', 'logo', 'favicon']
const SHADES = [[50, 'w', 0.95], [100, 'w', 0.9], [200, 'w', 0.75], [300, 'w', 0.6], [400, 'w', 0.3], [500, null, 0],
  [600, 'b', 0.15], [700, 'b', 0.3], [800, 'b', 0.45], [900, 'b', 0.6]]

// ---- colour maths (section 2.2) ----
const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
const rgbToHex = (c) => '#' + c.map((v) => v.toString(16).padStart(2, '0')).join('')
const mix = (c, target, t) => c.map((v) => Math.round(v * (1 - t) + target * t))
const lum = (c) => {
  const [r, g, b] = c.map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4 })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05) }
const foreground = (c) => (contrast(c, [255, 255, 255]) >= contrast(c, hexToRgb('#111827')) ? '#ffffff' : '#111827')

function colourVars(name, hex) {
  const base = hexToRgb(hex.toLowerCase())
  const out = [`  --brand-${name}: ${rgbToHex(base)};`, `  --brand-${name}-rgb: ${base.join(' ')};`,
    `  --brand-${name}-foreground: ${foreground(base)};`]
  for (const [shade, kind, t] of SHADES) {
    const c = kind === 'w' ? mix(base, 255, t) : kind === 'b' ? mix(base, 0, t) : base
    out.push(`  --brand-${name}-${shade}: ${rgbToHex(c)};`, `  --brand-${name}-${shade}-rgb: ${c.join(' ')};`)
  }
  return out
}

function brandCss(brand) {
  const fallback = SERIF.includes(brand.font) ? 'ui-serif, Georgia, serif' : 'ui-sans-serif, system-ui, sans-serif'
  return ['/* Generated by Vitara from src/config/brand.json. Do not edit: change brand.json instead. */', ':root {',
    ...colourVars('primary', brand.primary_color), ...colourVars('accent', brand.accent_color),
    `  --brand-font: "${brand.font}", ${fallback};`, '}', ''].join('\n')
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
function headBlock(brand) {
  const fam = brand.font.replace(/ /g, '+')
  return ['    <!-- vitara:brand:start -->', `    <title>${esc(brand.app_name)}</title>`,
    brand.tagline && `    <meta name="description" content="${esc(brand.tagline)}" />`,
    brand.favicon && `    <link rel="icon" href="${esc(brand.favicon)}" />`,
    '    <link rel="preconnect" href="https://fonts.googleapis.com" />',
    '    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />',
    `    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=${fam}:wght@400;500;600;700&display=swap" />`,
    '    <!-- vitara:brand:end -->'].filter(Boolean).join('\n')
}
const BLOCK_RE = /[ \t]*<!-- vitara:brand:start -->[\s\S]*?<!-- vitara:brand:end -->/

function generate() {
  const brand = readJson('src/config/brand.json')
  writeFileSync(p('src/styles/brand.css'), brandCss(brand))
  const html = readFileSync(p('index.html'), 'utf8')
  if (!BLOCK_RE.test(html)) throw new Error('index.html has no vitara:brand markers')
  writeFileSync(p('index.html'), html.replace(BLOCK_RE, headBlock(brand)))
  console.log('Wrote src/styles/brand.css and the index.html brand block.')
}

// ---- check ----
function check() {
  const errors = []
  const err = (m) => errors.push(m)

  const manifest = readJson('vitara.template.json')
  const extra = Object.keys(manifest).filter((k) => !['version', 'branding', 'locales'].includes(k))
  if (extra.length) err(`manifest: unknown fields ${extra.join(', ')}`)
  if (manifest.version !== 1) err('manifest: version must be 1')

  if (manifest.branding) {
    const brand = readJson('src/config/brand.json')
    const keys = Object.keys(brand)
    if (keys.join() !== BRAND_KEYS.join()) err(`brand.json: keys must be ${BRAND_KEYS.join(', ')}`)
    for (const k of ['primary_color', 'accent_color']) if (!/^#[0-9a-fA-F]{6}$/.test(brand[k] ?? '')) err(`brand.json: ${k} must be #rrggbb`)
    if (![...SANS, ...SERIF].includes(brand.font)) err(`brand.json: font "${brand.font}" is not in the allowed list`)
    for (const k of ['logo', 'favicon']) {
      const v = brand[k]
      if (v && !/^\/brand\/(logo|favicon)\.(png|jpg|webp)$/.test(v)) err(`brand.json: ${k} must be /brand/${k}.<png|jpg|webp> or ""`)
      if (v && !existsSync(p('public', v))) err(`brand.json: ${k} file public${v} is missing`)
    }
    const raw = readFileSync(p('src/config/brand.json'), 'utf8')
    if (raw !== JSON.stringify(brand, null, 2) + '\n') err('brand.json: must be 2-space JSON with a trailing newline')
    if (readFileSync(p('src/styles/brand.css'), 'utf8') !== brandCss(brand)) err('brand.css: out of date, run `node .vitara/template.mjs generate`')
    const html = readFileSync(p('index.html'), 'utf8')
    const m = html.match(BLOCK_RE)
    if (!m) err('index.html: missing vitara:brand markers')
    else {
      if (m[0].trim() !== headBlock(brand).trim()) err('index.html: brand block out of date, run `node .vitara/template.mjs generate`')
      const rest = html.replace(BLOCK_RE, '')
      if (/<title>|name="description"|rel="icon"/.test(rest)) err('index.html: title, description or favicon outside the brand block')
    }
    if (!/import ['"]\.\/styles\/brand\.css['"]/.test(readFileSync(p('src/main.tsx'), 'utf8'))) err('main.tsx: must import ./styles/brand.css')
  }

  if (manifest.locales) {
    const { default: def, available } = manifest.locales
    if (!Array.isArray(available) || available.length < 1 || available.length > 20) err('manifest: locales.available needs 1 to 20 codes')
    if (new Set(available).size !== available.length) err('manifest: locales.available has repeats')
    if (!available.includes(def)) err('manifest: locales.default must be in available')
    for (const c of available) if (!(c in CODES)) err(`manifest: unknown language code ${c}`)

    const cfg = readJson('src/config/locales.json')
    if (cfg.default !== def) err('locales.json: default differs from the manifest')
    if (cfg.available.map((l) => l.code).join() !== available.join()) err('locales.json: languages differ from the manifest (or order)')
    for (const l of cfg.available) if (CODES[l.code] && l.dir !== CODES[l.code]) err(`locales.json: ${l.code} must be ${CODES[l.code]}`)

    const flat = (o, pre = '') => Object.entries(o).flatMap(([k, v]) => (v && typeof v === 'object' ? flat(v, `${pre}${k}.`) : [[pre + k, v]]))
    const load = (code) => {
      const dir = p('src/locales', code)
      if (!existsSync(dir) || !statSync(dir).isDirectory()) { err(`locales: folder src/locales/${code}/ is missing`); return null }
      return Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
        .map((f) => [f, Object.fromEntries(flat(JSON.parse(readFileSync(join(dir, f), 'utf8'))))]))
    }
    const vars = (s) => [...String(s).matchAll(/\{\{(\w+)\}\}/g)].map((x) => x[1]).sort().join()
    const tags = (s) => (String(s).match(/<\/?em>/g) || []).join()
    const base = load(def)
    if (base) for (const code of available.filter((c) => c !== def)) {
      const other = load(code)
      if (!other) continue
      if (Object.keys(other).join() !== Object.keys(base).join()) { err(`locales/${code}: files differ from ${def}`); continue }
      for (const [file, keys] of Object.entries(base)) {
        for (const [k, v] of Object.entries(keys)) {
          const o = other[file][k]
          if (o === undefined) err(`locales/${code}/${file}: missing ${k}`)
          else if (!o) err(`locales/${code}/${file}: empty ${k}`)
          else if (vars(o) !== vars(v)) err(`locales/${code}/${file}: placeholders differ in ${k}`)
          else if (tags(o) !== tags(v)) err(`locales/${code}/${file}: <em> tags differ in ${k}`)
        }
        for (const k of Object.keys(other[file])) if (!(k in keys)) err(`locales/${code}/${file}: extra key ${k}`)
      }
    }
  }

  if (errors.length) { console.error(errors.map((e) => '✗ ' + e).join('\n')); process.exit(1) }
  console.log('✓ Template follows the Vitara template contract v1.')
}

const cmd = process.argv[2]
if (cmd === 'generate') generate()
else if (cmd === 'check') check()
else { console.error('usage: node .vitara/template.mjs <generate|check>'); process.exit(2) }
